package com.lumi.camera.filter

internal data class RgbTint(
    val r: Float = 0f,
    val g: Float = 0f,
    val b: Float = 0f,
) {
    fun clamped(): RgbTint = RgbTint(
        r = r.coerceIn(-0.25f, 0.25f),
        g = g.coerceIn(-0.25f, 0.25f),
        b = b.coerceIn(-0.25f, 0.25f),
    )

    fun lerp(target: RgbTint, t: Float): RgbTint = RgbTint(
        r = r + (target.r - r) * t,
        g = g + (target.g - g) * t,
        b = b + (target.b - b) * t,
    )
}

internal data class FilterGrade(
    val exposure: Float = 0f,
    val contrast: Float = 0f,
    val highlights: Float = 0f,
    val shadows: Float = 0f,
    val fade: Float = 0f,
    val temperature: Float = 0f,
    val tint: Float = 0f,
    val saturation: Float = 0f,
    val vibrance: Float = 0f,
    val skinProtect: Float = 0.65f,
    val shadowTint: RgbTint = RgbTint(),
    val highlightTint: RgbTint = RgbTint(),
    val glow: Float = 0f,
    val grain: Float = 0f,
    val vignette: Float = 0f,
    val intensity: Float = 0f,
) {
    val isIdentity: Boolean
        get() = intensity <= 0.005f

    fun clamped(): FilterGrade = copy(
        exposure = exposure.coerceIn(-0.5f, 0.5f),
        contrast = contrast.coerceIn(-0.35f, 0.45f),
        highlights = highlights.coerceIn(-0.6f, 0.35f),
        shadows = shadows.coerceIn(-0.3f, 0.6f),
        fade = fade.coerceIn(0f, 0.25f),
        temperature = temperature.coerceIn(-0.4f, 0.4f),
        tint = tint.coerceIn(-0.3f, 0.3f),
        saturation = saturation.coerceIn(-1f, 0.4f),
        vibrance = vibrance.coerceIn(-0.3f, 0.4f),
        skinProtect = skinProtect.coerceIn(0f, 1f),
        shadowTint = shadowTint.clamped(),
        highlightTint = highlightTint.clamped(),
        glow = glow.coerceIn(0f, 0.35f),
        grain = grain.coerceIn(0f, 0.25f),
        vignette = vignette.coerceIn(0f, 0.35f),
        intensity = intensity.coerceIn(0f, 1f),
    )

    fun lerp(target: FilterGrade, t: Float): FilterGrade {
        val f = t.coerceIn(0f, 1f)
        fun mix(a: Float, b: Float) = a + (b - a) * f
        return FilterGrade(
            exposure = mix(exposure, target.exposure),
            contrast = mix(contrast, target.contrast),
            highlights = mix(highlights, target.highlights),
            shadows = mix(shadows, target.shadows),
            fade = mix(fade, target.fade),
            temperature = mix(temperature, target.temperature),
            tint = mix(tint, target.tint),
            saturation = mix(saturation, target.saturation),
            vibrance = mix(vibrance, target.vibrance),
            skinProtect = mix(skinProtect, target.skinProtect),
            shadowTint = shadowTint.lerp(target.shadowTint, f),
            highlightTint = highlightTint.lerp(target.highlightTint, f),
            glow = mix(glow, target.glow),
            grain = mix(grain, target.grain),
            vignette = mix(vignette, target.vignette),
            intensity = mix(intensity, target.intensity),
        )
    }

    companion object {
        val IDENTITY = FilterGrade(intensity = 0f)
    }
}

